/**
 * Pre-renders every formula in the pack to KaTeX HTML at build time,
 * so the site ships zero runtime KaTeX JS (only the stylesheet).
 * Run: bun run scripts/gen-formula-html.ts
 */
import katex from "katex";
import { FORMULAS } from "../src/content/formulas";
import { writeFileSync } from "node:fs";

const map: Record<string, string> = {};
for (const f of FORMULAS) {
  try {
    map[f.id] = katex.renderToString(f.latex, {
      displayMode: true,
      throwOnError: true,
      strict: false,
      output: "html",
    });
  } catch (e) {
    console.error(`Failed to render ${f.id}:`, e);
    process.exit(1);
  }
}

const out = `// AUTO-GENERATED by scripts/gen-formula-html.ts - do not edit by hand.
export const FORMULA_HTML: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;
writeFileSync("src/content/formulaHtml.ts", out);
console.log(`Rendered ${Object.keys(map).length} formulas -> src/content/formulaHtml.ts`);
